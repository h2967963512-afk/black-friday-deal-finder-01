// Totals the board shows at the top, computed from the deals above.
export function boardStats(list) {
  const totalSaving = list.reduce((sum, d) => sum + (d.was - d.price), 0);
  const avgDiscount =
    list.reduce((sum, d) => sum + (1 - d.price / d.was), 0) / list.length;
  const newLows = list.filter((d) => d.verdict === "new-low").length;
  return {
    count: list.length,
    totalSaving: Math.round(totalSaving * 100) / 100,
    avgDiscount: Math.round(avgDiscount * 1000) / 10,
    newLows,
  };
}
